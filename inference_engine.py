    @staticmethod
    def extract_prediction_instances(mask_binary: np.ndarray) -> List[Dict[str, Any]]:
        """Split a binary prediction into complete connected components."""
        binary = (mask_binary > 0).astype(np.uint8)
        count, labels, stats, centroids = cv2.connectedComponentsWithStats(binary, connectivity=8)
        height, width = binary.shape[:2]
        instances = []
        for label in range(1, count):
            x, y, w, h, area = stats[label].tolist()
            instances.append({"instance_id": label, "mask": (labels == label).astype(np.uint8), "area_pixels": int(area), "area_ratio": float(area / (height * width)), "bbox": [int(x), int(y), int(w), int(h)], "centroid_x": float(centroids[label][0]), "centroid_y": float(centroids[label][1])})
        return instances

    @staticmethod
    def _instance_in_position(instance: Dict[str, Any], position: Optional[str], width: int, height: int) -> bool:
        position = str(position or "Not specified")
        if position == "Not specified":
            return True
        x, y = float(instance["centroid_x"]), float(instance["centroid_y"])
        return {"left": x < width / 2, "right": x >= width / 2, "top": y < height / 2, "bottom": y >= height / 2, "upper-left": x < width / 2 and y < height / 2, "upper-right": x >= width / 2 and y < height / 2, "lower-left": x < width / 2 and y >= height / 2, "lower-right": x >= width / 2 and y >= height / 2, "center": width * .25 <= x < width * .75 and height * .25 <= y < height * .75}.get(position, True)

    @staticmethod
    def union_instance_masks(instances: List[Dict[str, Any]], height: int, width: int) -> np.ndarray:
        union = np.zeros((height, width), dtype=np.uint8)
        for instance in instances:
            union |= instance["mask"].astype(np.uint8)
        return union

    @staticmethod
    def _region_mask(
        height: int,
        width: int,
        position: Optional[str],
    ) -> np.ndarray:
        mask = np.ones((height, width), dtype=bool)
        position = str(position or "Not specified")
        if position == "Not specified":
            return mask
        y, x = np.ogrid[:height, :width]
        conditions = {
            "left": x < width / 2, "right": x >= width / 2,
            "top": y < height / 2, "bottom": y >= height / 2,
            "upper-left": (x < width / 2) & (y < height / 2),
            "upper-right": (x >= width / 2) & (y < height / 2),
            "lower-left": (x < width / 2) & (y >= height / 2),
            "lower-right": (x >= width / 2) & (y >= height / 2),
            "center": (x >= width * .25) & (x < width * .75) & (y >= height * .25) & (y < height * .75),
        }
        return conditions.get(position, mask)

    @staticmethod
    def _draw_region_guide(
        image: Optional[np.ndarray],
        position: Optional[str],
    ) -> Optional[np.ndarray]:
        if image is None or not position or position == "Not specified":
            return image
        out = image.copy()
        h, w = out.shape[:2]
        color = (255, 220, 0)
        thickness = 1
        if position in {"left", "right", "upper-left", "upper-right", "lower-left", "lower-right"}:
            cv2.line(out, (w // 2, 0), (w // 2, h - 1), color, thickness)
        if position in {"top", "bottom", "upper-left", "upper-right", "lower-left", "lower-right"}:
            cv2.line(out, (0, h // 2), (w - 1, h // 2), color, thickness)
        if position == "center":
            cv2.rectangle(out, (int(w * .25), int(h * .25)), (int(w * .75) - 1, int(h * .75) - 1), color, thickness)
        return out

    @staticmethod
    def _make_visuals(
        original_rgb: np.ndarray,
        mask_binary: np.ndarray,
    ) -> Tuple[np.ndarray, np.ndarray, np.ndarray]:
        mask_255 = (
            mask_binary.astype(np.uint8)
            * 255
        )

        overlay = original_rgb.copy()
        fg = mask_binary.astype(bool)

        if fg.any():
            highlight = np.zeros_like(
                original_rgb,
                dtype=np.uint8,
            )
            highlight[..., 0] = 255

            blended = (
                0.55
                * original_rgb.astype(np.float32)
                + 0.45
                * highlight.astype(np.float32)
            )
            overlay[fg] = np.clip(
                blended[fg],
                0,
                255,
            ).astype(np.uint8)

        contour = original_rgb.copy()
        contours, _ = cv2.findContours(
            mask_255,
            cv2.RETR_EXTERNAL,
            cv2.CHAIN_APPROX_SIMPLE,
        )

        if contours:
            cv2.drawContours(
                contour,
                contours,
                contourIdx=-1,
                color=(0, 255, 0),
                thickness=2,
            )

        return mask_255, overlay, contour

    @staticmethod
    def _make_gt_comparison(
        original_rgb: np.ndarray,
        pred_mask: np.ndarray,
        gt_mask: Optional[np.ndarray],
    ) -> Optional[np.ndarray]:
        """
        Color-coded GT vs prediction overlay:
          green = TP (prediction overlaps GT)
          red   = FP (predicted defect not in GT)
          blue  = FN (GT defect missed by prediction)
        """
        if gt_mask is None:
            return None

        pred = pred_mask.astype(bool)
        gt = gt_mask.astype(bool)

        tp = np.logical_and(pred, gt)
        fp = np.logical_and(
            pred,
            np.logical_not(gt),
        )
        fn = np.logical_and(
            np.logical_not(pred),
            gt,
        )

        # Slightly darken the original image so the comparison colors stand out.
        out = np.clip(
            original_rgb.astype(np.float32) * 0.48,
            0,
            255,
        ).astype(np.uint8)

        def paint(mask, rgb):
            if not bool(mask.any()):
                return
            color = np.zeros_like(
                original_rgb,
                dtype=np.uint8,
            )
            color[..., 0] = rgb[0]
            color[..., 1] = rgb[1]
            color[..., 2] = rgb[2]

            blended = (
                0.22
                * original_rgb.astype(np.float32)
                + 0.78
                * color.astype(np.float32)
            )
            out[mask] = np.clip(
                blended[mask],
                0,
                255,
            ).astype(np.uint8)

        paint(tp, (0, 255, 0))
        paint(fp, (255, 0, 0))
        paint(fn, (0, 128, 255))

        return out

    def _save_result_package(
        self,
        original_rgb: np.ndarray,
        mask_255: np.ndarray,
        overlay_rgb: np.ndarray,
        contour_rgb: np.ndarray,
        metadata: Dict[str, Any],
        gt_mask_255: Optional[np.ndarray] = None,
        comparison_rgb: Optional[np.ndarray] = None,
    ) -> str:
        output_root = (
            self.root
            / "ui_outputs"
        )
        output_root.mkdir(
            parents=True,
            exist_ok=True,
        )

        run_id = (
            time.strftime("%Y%m%d_%H%M%S")
            + "_"
            + uuid.uuid4().hex[:8]
        )

        run_dir = output_root / run_id
        run_dir.mkdir(
            parents=True,
            exist_ok=False,
        )

        original_path = run_dir / "original.png"
        mask_path = run_dir / "predicted_mask.png"
        overlay_path = run_dir / "prediction_overlay.png"
        contour_path = run_dir / "contour.png"
        gt_path = run_dir / "ground_truth_mask.png"
        comparison_path = run_dir / "gt_vs_prediction.png"
        metadata_path = run_dir / "metadata.json"

        _write_image(
            str(original_path),
            cv2.cvtColor(
                original_rgb,
                cv2.COLOR_RGB2BGR,
            ),
        )
        _write_image(
            str(mask_path),
            mask_255,
        )
        _write_image(
            str(overlay_path),
            cv2.cvtColor(
                overlay_rgb,
                cv2.COLOR_RGB2BGR,
            ),
        )
        _write_image(
            str(contour_path),
            cv2.cvtColor(
                contour_rgb,
                cv2.COLOR_RGB2BGR,
            ),
        )

        package_files = [
            original_path,
            mask_path,
            overlay_path,
            contour_path,
        ]

        if gt_mask_255 is not None:
            _write_image(
                str(gt_path),
                gt_mask_255,
            )
            package_files.append(gt_path)

        if comparison_rgb is not None:
            _write_image(
                str(comparison_path),
                cv2.cvtColor(
                    comparison_rgb,
                    cv2.COLOR_RGB2BGR,
                ),
            )
            package_files.append(
                comparison_path
            )

        with open(
            metadata_path,
            "w",
            encoding="utf-8",
        ) as f:
            json.dump(
                metadata,
                f,
                ensure_ascii=False,
                indent=2,
            )

        package_files.append(
            metadata_path
        )

        zip_path = (
            output_root
            / f"{run_id}_results.zip"
        )

        with zipfile.ZipFile(
            zip_path,
            "w",
            compression=zipfile.ZIP_DEFLATED,
        ) as zf:
            for path in package_files:
                zf.write(
                    path,
                    arcname=path.name,
                )

        return str(zip_path)

