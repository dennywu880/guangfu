    @staticmethod
    def _format_value(
        key: str,
        value: Any,
    ) -> str:
        if value is None:
            return "N/A"

        if isinstance(value, bool):
            return str(value)

        if isinstance(value, float):
            if "Ratio" in key:
                return f"{value:.6f}"
            if "Probability" in key:
                return f"{value:.6f}"
            if key in {
                "Pixel Accuracy",
                "Dice",
                "IoU",
                "Precision",
                "Recall",
                "Specificity",
                "F1",
            }:
                return f"{value:.4f}"
            if "Time" in key:
                return f"{value:.3f}"
            if "Threshold" in key:
                return f"{value:.4f}"
            return f"{value:.6f}"

        return str(value)

