def _load_final_baseline_module():
    """
    Load 43_final_testB_gate_v2_and_m2_metrics.py by file path.

    The filename starts with a number, so using importlib keeps the UI tied
    to the already-validated final TestB implementation instead of creating
    an unrelated second copy of its constants/checkpoint logic.
    """
    path = ROOT / "43_final_testB_gate_v2_and_m2_metrics.py"

    if not path.exists():
        raise FileNotFoundError(
            "Final TestB baseline script not found:\n"
            f"{path}"
        )

    module_name = "_tg_unet_final_testb_baseline"
    spec = importlib.util.spec_from_file_location(
        module_name,
        str(path),
    )

    if spec is None or spec.loader is None:
        raise RuntimeError(
            "Could not create import specification for:\n"
            f"{path}"
        )

    module = importlib.util.module_from_spec(spec)
    sys.modules[module_name] = module
    spec.loader.exec_module(module)
    return module


BASELINE = _load_final_baseline_module()


class _PooledTextOnlyEncoder(nn.Module):
    """
    Tiny placeholder used inside expert models after their checkpoint has
    been loaded. Expert inference always receives pooled_text generated by
    the General model's real frozen BERT, so retaining three duplicate BERT
    copies is unnecessary for single-image UI inference.

    The .bert attribute is kept because TextGuidedUNet.train()/eval() expects
    self.text_encoder.bert.eval().
    """

    def __init__(self):
        super().__init__()
        self.bert = nn.Identity()

    def forward(self, *args, **kwargs):
        raise RuntimeError(
            "Expert text encoder placeholder cannot encode raw text. "
            "Pass pooled_text from the General model."
        )


class DefectInferenceEngine:
    """
    Single-image inference wrapper for the frozen final system:

        image + text
        -> General model
        -> Presence Gate v2
        -> frozen Router
        -> Ultra/Tiny/Larger expert
        -> binary mask

    All checkpoints are loaded once during engine construction.
    """

    RELATION_CANDIDATES = [
        "not connected to busbar",
        "connected to busbar",
        "not intersected with busbar",
        "intersected with busbar",
        "not touching in busbar",
        "touching in busbar",
    ]

    # These are deliberately restricted to words already handled by the
    # frozen Router in 43.py.
    SIZE_CANDIDATES = [
        "tiny",
        "small",
        "medium",
        "moderate",
        "average",
        "large",
        "big",
        "miniature",
        "little",
    ]

    POSITION_CANDIDATES = [
        "left",
        "right",
        "upper",
        "lower",
        "top",
        "bottom",
        "center",
        "middle",
        "corner",
        "region",
    ]

    POSITION_CHOICES = [
        "Not specified",
        "left",
        "right",
        "top",
        "bottom",
        "center",
        "upper-left",
        "upper-right",
        "lower-left",
        "lower-right",
    ]

    POSITION_TEMPLATES = {
        "left": "on the left side",
        "right": "on the right side",
        "top": "in the upper part",
        "bottom": "in the lower part",
        "center": "in the center",
        "upper-left": "in the upper-left region",
        "upper-right": "in the upper-right region",
        "lower-left": "in the lower-left region",
        "lower-right": "in the lower-right region",
    }

    def __init__(self):
        self.root = ROOT
        self.use_shared_moe = os.environ.get("TG_SHARED_MOE", "0") == "1"
        self.shared_moe = None
        self.device = torch.device(
            "cuda" if torch.cuda.is_available() else "cpu"
        )

        self.general_model = None
        self.gate = None
        self.experts: Dict[str, nn.Module] = {}
        self._resident_expert: Optional[str] = None

        self.hook = None
        self.detected_hook_name = None

        self.gate_mean = None
        self.gate_std = None
        self.gate_threshold = None

        self.catalog_error = ""
        self.defect_choices: List[str] = []
        self.position_choices: List[str] = ["Not specified"]
        self.size_choices: List[str] = ["Not specified"]
        self.relation_choices: List[str] = ["Not specified"]
        self._defect_by_label: Dict[str, Dict[str, Any]] = {}
        self._sentence_index: Dict[
            Tuple[int, Optional[str], Optional[str]],
            Tuple[int, str]
        ] = {}
        self._category_fallback: Dict[int, Tuple[int, str]] = {}

        # Dataset-backed Ground Truth lookup for single-image evaluation.
        # Keys use the original dataset image filename + normalized expression.
        self._image_meta_by_filename: Dict[str, Dict[str, Any]] = {}
        self._ann_by_id: Dict[int, Dict[str, Any]] = {}
        self._gt_sentence_index: Dict[
            Tuple[str, str],
            List[Dict[str, Any]],
        ] = {}
        # Compact all-split reference index used by condition-aware GT.
        self._refs_by_filename: Dict[str, List[Dict[str, Any]]] = {}

        self._check_required_files()
        self._load_models_once()
        self._load_structured_query_catalog()

    # ------------------------------------------------------------------
    # Initialization
    # ------------------------------------------------------------------

    def _check_required_files(self):
        required = [
            BASELINE.GENERAL_CHECKPOINT,
            BASELINE.PRESENCE_GATE_CHECKPOINT,
            *BASELINE.EXPERT_CHECKPOINTS.values(),
        ]

        missing = [
            str(path)
            for path in required
            if not Path(path).exists()
        ]

        if missing:
            joined = "\n".join(missing)
            raise FileNotFoundError(
                "Required checkpoint(s) missing:\n"
                f"{joined}"
            )

    def _load_models_once(self):
        print()
        print("=" * 88)
        print("Initializing Text-Guided Photovoltaic Defect Segmentation UI")
        print("=" * 88)
        print(f"Device: {self.device}")

        if self.device.type == "cuda":
            print(f"GPU: {torch.cuda.get_device_name(0)}")
        else:
            print("CUDA unavailable, falling back to CPU.")

        try:
            print("\n[1/5] Loading General model...")
            self.general_model = BASELINE.load_seg_model(
                BASELINE.GENERAL_CHECKPOINT,
                self.device,
            )
            self.general_model.eval()
            print("General loaded.")

            print("\n[2/5] Loading Presence Gate v2...")
            (
                self.gate,
                feature_mean,
                feature_std,
                hook_name,
                self.gate_threshold,
            ) = BASELINE.load_presence_gate(self.device)
            self.gate.eval()

            self.gate_mean = torch.as_tensor(
                feature_mean,
                dtype=torch.float32,
                device=self.device,
            ).view(1, -1)

            self.gate_std = torch.as_tensor(
                feature_std,
                dtype=torch.float32,
                device=self.device,
            ).view(1, -1)

            self.detected_hook_name, hook_module = (
                BASELINE.find_deep_image_module(
                    self.general_model,
                    preferred_name=hook_name,
                )
            )
            self.hook = BASELINE.FeatureHook(hook_module)
            print(
                "Presence Gate loaded. "
                f"hook={self.detected_hook_name}, "
                f"threshold={self.gate_threshold:.4f}"
            )

            if self.use_shared_moe:
                print("\n[3/5] Loading one shared encoder and three expert heads...")
                self.shared_moe = SharedMoE.from_checkpoints(
                    BASELINE.CHECKPOINT_DIR, self.device,
                    general=self.general_model,
                    expert_backbone=os.environ.get("TG_EXPERT_BACKBONE") or None,
                )
                trained_heads = os.environ.get("TG_SHARED_HEADS")
                if trained_heads:
                    self.shared_moe.load_heads(trained_heads)
                    print(f"Loaded fine-tuned shared heads: {trained_heads}")
                repair_checkpoint = os.environ.get("TG_SHARED_REPAIR")
                if repair_checkpoint:
                    self.shared_moe.load_repair(repair_checkpoint)
                    print(f"Loaded shared-encoder repair: {repair_checkpoint}")
                # Gate feature hooks refer to this very same general model.
                self.hook.close()
                self.general_model = self.shared_moe.general
                self.detected_hook_name, hook_module = BASELINE.find_deep_image_module(
                    self.general_model, preferred_name=hook_name,
                )
                self.hook = BASELINE.FeatureHook(hook_module)
                print("Shared encoder and expert heads loaded.")
                return

            # Experts are loaded once on CPU, then their duplicate frozen BERT
            # is replaced by a tiny placeholder. One selected expert is moved
            # to CUDA on demand; changing branch swaps the resident expert.
            cpu = torch.device("cpu")

            for step, branch in enumerate(
                BASELINE.GROUPS,
                start=3,
            ):
                path = BASELINE.EXPERT_CHECKPOINTS[branch]
                print(
                    f"\n[{step}/5] Loading {branch} expert..."
                )
                expert = BASELINE.load_seg_model(
                    path,
                    cpu,
                )

                # Checkpoint has already been loaded strictly at this point.
                # From now on expert forward uses pooled_text only.
                expert.text_encoder = _PooledTextOnlyEncoder()
                expert.eval()
                self.experts[branch] = expert

                gc.collect()
                print(f"{branch} expert loaded.")

            if self.device.type == "cuda":
                torch.cuda.empty_cache()

            print("\nAll five frozen components loaded successfully.")

        except OSError as exc:
            message = str(exc)
            if (
                "bert-base-uncased" in message
                or "local_files_only" in message
                or "couldn't connect" in message.lower()
            ):
                raise RuntimeError(
                    "Model initialization failed because the local "
                    "bert-base-uncased tokenizer/model cache is unavailable. "
                    "Keep the existing offline cache and run with "
                    "HF_HUB_OFFLINE=1."
                ) from exc
            raise

    def _activate_expert(self, branch: str) -> nn.Module:
        if branch not in self.experts:
            raise KeyError(f"Unknown expert branch: {branch}")

        expert = self.experts[branch]

        if self.device.type != "cuda":
            return expert

        if self._resident_expert == branch:
            return expert

        if self._resident_expert is not None:
            old = self.experts[self._resident_expert]
            old.to("cpu")

        torch.cuda.empty_cache()

        expert.to(self.device)
        expert.eval()
        self._resident_expert = branch
        return expert

    # ------------------------------------------------------------------
    # Dataset-driven structured text catalog
    # ------------------------------------------------------------------

    @staticmethod
    def _normalize_expression(text: str) -> str:
        """Normalize dataset/user expressions for conservative exact GT lookup."""
        return re.sub(
            r"[^a-z0-9]+",
            " ",
            str(text or "").lower(),
        ).strip()

    @staticmethod
    def _contains_word(text: str, word: str) -> bool:
        return (
            re.search(
                r"\b" + re.escape(word.lower()) + r"\b",
                text.lower(),
            )
            is not None
        )

    def _detect_size_word(self, text: str) -> Optional[str]:
        for word in self.SIZE_CANDIDATES:
            if self._contains_word(text, word):
                return word
        return None

    def _detect_relation(self, text: str) -> Optional[str]:
        low = text.lower()

        # Negative phrases must be checked before positive substrings.
        for phrase in self.RELATION_CANDIDATES:
            if phrase in low:
                return phrase

        return None

    def _load_structured_query_catalog(self):
        instances_path = (
            self.root
            / "datasets"
            / "grefcoco"
            / "instances.json"
        )
        grefs_path = (
            self.root
            / "datasets"
            / "grefcoco"
            / "grefs(unc).json"
        )

        if not instances_path.exists() or not grefs_path.exists():
            self.catalog_error = (
                "Structured query metadata unavailable because "
                "datasets/grefcoco/instances.json or grefs(unc).json "
                "was not found. Free-text inference still works."
            )
            print("\nWARNING:", self.catalog_error)
            return

        try:
            with open(
                instances_path,
                "r",
                encoding="utf-8",
            ) as f:
                instances = json.load(f)

            with open(
                grefs_path,
                "r",
                encoding="utf-8",
            ) as f:
                refs = json.load(f)

            categories = {
                int(item["id"]): item
                for item in instances.get("categories", [])
            }

            # Compact COCO lookup tables used to reconstruct the real GT mask.
            self._image_meta_by_filename = {
                str(item.get("file_name", "")).lower(): {
                    "id": int(item["id"]),
                    "file_name": str(item.get("file_name", "")),
                    "height": int(item.get("height", 0)),
                    "width": int(item.get("width", 0)),
                }
                for item in instances.get("images", [])
                if item.get("file_name") is not None
            }

            self._ann_by_id = {
                int(ann["id"]): ann
                for ann in instances.get("annotations", [])
            }

            # Real categories come directly from instances.json.
            for cid in sorted(categories):
                item = categories[cid]
                name = str(item.get("name", "")).strip()
                supercategory = str(
                    item.get("supercategory", "")
                ).strip()

                if name and supercategory:
                    label = f"{name} {supercategory}"
                else:
                    label = name or supercategory or f"Category {cid}"

                self._defect_by_label[label] = {
                    "id": cid,
                    "name": name,
                    "supercategory": supercategory,
                }

            self.defect_choices = list(
                self._defect_by_label.keys()
            )

            size_counts = {
                word: 0
                for word in self.SIZE_CANDIDATES
            }
            relation_counts = {
                phrase: 0
                for phrase in self.RELATION_CANDIDATES
            }
            position_counts = {
                word: 0
                for word in self.POSITION_CANDIDATES
            }

            for ref in refs:
                # ----------------------------------------------------------
                # Auto-GT index: use ALL splits, but only for evaluation.
                # We deliberately require an exact normalized expression for
                # the same image filename. If the dataset itself contains an
                # ambiguous duplicate expression, automatic GT is disabled for
                # that query rather than guessing the target.
                # ----------------------------------------------------------
                ref_file_name = str(ref.get("file_name", "")).strip()
                ref_ann_ids = ref.get("ann_id", [])
                if not isinstance(ref_ann_ids, list):
                    ref_ann_ids = [ref_ann_ids]

                ref_payload = {
                    "ref_id": int(ref.get("ref_id", -1)),
                    "split": str(ref.get("split", "")),
                    "file_name": ref_file_name,
                    "ann_ids": [
                        int(aid)
                        for aid in ref_ann_ids
                        if aid is not None
                    ],
                    "no_target": bool(ref.get("no_target", False)),
                    "category_ids": [
                        int(cid)
                        for cid in (ref.get("category_id", []) if isinstance(ref.get("category_id", []), list) else [ref.get("category_id")])
                        if cid is not None
                    ],
                    "sentences": [
                        str(sentence.get("sent", sentence.get("raw", ""))).strip()
                        for sentence in ref.get("sentences", [])
                        if str(sentence.get("sent", sentence.get("raw", ""))).strip()
                    ],
                }

                if ref_file_name:
                    self._refs_by_filename.setdefault(
                        ref_file_name.lower(), []
                    ).append(ref_payload)

                if ref_file_name:
                    for gt_sentence in ref.get("sentences", []):
                        gt_text = str(
                            gt_sentence.get(
                                "sent",
                                gt_sentence.get("raw", ""),
                            )
                        ).strip()
                        gt_norm = self._normalize_expression(gt_text)
                        if not gt_norm:
                            continue

                        key = (
                            ref_file_name.lower(),
                            gt_norm,
                        )
                        self._gt_sentence_index.setdefault(
                            key,
                            [],
                        ).append(ref_payload)

                # Structured-query vocabulary is learned from TRAIN only.
                # Do not use TestB text to define UI options/templates.
                if str(ref.get("split", "")) != "train":
                    continue

                if bool(ref.get("no_target", False)):
                    continue

                category_ids = ref.get("category_id", [])
                if not isinstance(category_ids, list):
                    category_ids = [category_ids]

                category_ids = [
                    int(cid)
                    for cid in category_ids
                    if int(cid) in categories
                ]

                for sentence in ref.get("sentences", []):
                    text = str(
                        sentence.get(
                            "sent",
                            sentence.get("raw", ""),
                        )
                    ).strip()

                    if not text:
                        continue

                    low = text.lower()

                    for word in size_counts:
                        if self._contains_word(text, word):
                            size_counts[word] += 1

                    relation = self._detect_relation(text)
                    if relation is not None:
                        relation_counts[relation] += 1

                    for word in position_counts:
                        if self._contains_word(text, word):
                            position_counts[word] += 1

                    size_word = self._detect_size_word(text)

                    for cid in category_ids:
                        category = categories[cid]
                        category_name = str(
                            category.get("name", "")
                        ).lower()
                        supercategory = str(
                            category.get("supercategory", "")
                        ).lower()

                        # Prefer actual training sentences that explicitly say
                        # the category instead of generic "all defects".
                        explicit_score = 0
                        if (
                            category_name
                            and category_name in low
                        ):
                            explicit_score += 2
                        if (
                            supercategory
                            and supercategory in low
                        ):
                            explicit_score += 1

                        key = (
                            cid,
                            size_word,
                            relation,
                        )

                        old = self._sentence_index.get(key)
                        if (
                            old is None
                            or explicit_score > old[0]
                        ):
                            self._sentence_index[key] = (
                                explicit_score,
                                text,
                            )

                        old_fallback = self._category_fallback.get(cid)
                        if (
                            old_fallback is None
                            or explicit_score > old_fallback[0]
                        ):
                            self._category_fallback[cid] = (
                                explicit_score,
                                text,
                            )

            # Keep the UI compact and Router-safe: these canonical size words
            # are all real dataset words and are explicitly parsed by 43.py.
            canonical_sizes = [
                "tiny",
                "little",
                "small",
                "large",
            ]
            self.size_choices = ["Not specified"] + [
                word
                for word in canonical_sizes
                # Keep the requested canonical choices available even when a
                # particular training split did not contain every wording.
                # They are text conditions, not claims of spatial training.
                if word in {"tiny", "little", "small", "large"}
            ]

            self.relation_choices = ["Not specified"] + [
                phrase
                for phrase in self.RELATION_CANDIDATES
                if relation_counts.get(phrase, 0) > 0
            ]

            # Position is a semantic text-condition supplement. It is not
            # presented as a separately validated spatial classifier.
            self.position_choices = list(self.POSITION_CHOICES)

            print()
            print(
                "Structured query catalog loaded from dataset JSON:"
            )
            print(
                f"  defect types   = {len(self.defect_choices)}"
            )
            print(
                f"  size choices   = {self.size_choices}"
            )
            print(
                f"  relation count = "
                f"{len(self.relation_choices) - 1}"
            )

            print(f"  position choices = {self.position_choices}")

            # Release the large JSON structures.
            del instances
            del refs
            gc.collect()

        except Exception as exc:
            self.catalog_error = (
                "Structured query catalog failed to load: "
                f"{exc}"
            )
            print("\nWARNING:", self.catalog_error)

    def get_structured_options(self) -> Dict[str, List[str]]:
        return {
            "defect_types": list(self.defect_choices),
            "positions": list(self.position_choices),
            "sizes": list(self.size_choices),
            "relations": list(self.relation_choices),
        }

    def build_expression(
        self,
        defect_type: str,
        position: str = "Not specified",
        size: str = "Not specified",
        relation: str = "Not specified",
    ) -> str:
        if not defect_type:
            raise ValueError(
                "Please select a Defect Type or enter free text."
            )

        if defect_type not in self._defect_by_label:
            raise ValueError(
                f"Unknown dataset defect type: {defect_type}"
            )

        info = self._defect_by_label[defect_type]
        cid = int(info["id"])

        size_word = None
        if size and size != "Not specified":
            size_word = size.lower()

        relation_phrase = None
        if relation and relation != "Not specified":
            relation_phrase = relation.lower()

        # Prefer a sentence that literally occurred in the dataset with the
        # chosen category/size/relation combination.
        candidate = self._sentence_index.get(
            (cid, size_word, relation_phrase)
        )
        if candidate is not None:
            return candidate[1]

        # If some attributes are unspecified, try the category fallback.
        if (
            size_word is None
            and relation_phrase is None
            and cid in self._category_fallback
        ):
            return self._category_fallback[cid][1]

        # Otherwise compose a sentence using the dataset's dominant grammar.
        name = info["name"]
        supercategory = info["supercategory"]

        parts = [
            f"The {name} type {supercategory} defect"
        ]

        if relation_phrase is not None:
            parts.append(relation_phrase)

        if size_word is not None:
            parts.append(f"with {size_word} size")

        position_phrase = self.POSITION_TEMPLATES.get(
            str(position or "").lower()
        )
        if position_phrase:
            parts.append(position_phrase)

        parts.append("in the EL image")

        return " ".join(parts)

    def parse_expression_fields(self, text: str) -> Dict[str, Optional[str]]:
        """Parse the four supported query fields without network services.

        The parser deliberately returns only canonical English values.  It is
        used for UI locking, while inference always receives the composed
        English final query.
        """
        raw = str(text or "").lower()
        normalized = self._normalize_expression(text)
        result: Dict[str, Optional[str]] = {
            "defect_type": None,
            "size": None,
            "position": None,
            "busbar_relation": None,
        }
        # _normalize_expression intentionally strips non-ASCII characters for
        # exact dataset lookup, so it can be empty for a valid Chinese query.
        if not raw.strip():
            return result

        # Chinese aliases are resolved locally into the same English
        # canonical values.  Negated forms intentionally precede positives.
        chinese_relations = [
            (("没有与主栅线连接", "未与主栅线连接", "不与主栅线连接", "与主栅线不相连", "未连接主栅线"), "not connected to busbar"),
            (("没有接触主栅线", "未接触主栅线", "不接触主栅线"), "not touching busbar"),
            (("与主栅线相交", "和主栅线相交", "与主栅线交叉", "穿过主栅线"), "intersected with busbar"),
            (("与主栅线连接", "连接主栅线", "和主栅线相连", "与主栅相连"), "connected to busbar"),
            (("接触主栅线", "与主栅线接触", "碰到主栅线"), "touching busbar"),
        ]
        for aliases, value in chinese_relations:
            if any(alias in raw for alias in aliases):
                result["busbar_relation"] = value
                break

        # Longer negative/specific English phrases must precede substrings.
        relation_patterns = [
            ("not connected to busbar", "not connected to busbar"),
            ("not touching busbar", "not touching busbar"),
            ("not touching in busbar", "not touching busbar"),
            ("not intersected with busbar", "not intersected with busbar"),
            ("intersected with busbar", "intersected with busbar"),
            ("connected to busbar", "connected to busbar"),
            ("touching busbar", "touching busbar"),
            ("touching in busbar", "touching busbar"),
        ]
        for phrase, value in relation_patterns:
            if result["busbar_relation"] is None and phrase in normalized:
                result["busbar_relation"] = value
                break

        chinese_sizes = [
            (("极细小", "微小", "极小", "很小"), "tiny"),
            (("较小",), "little"),
            (("小型", "小缺陷", "小"), "small"),
            (("大尺寸", "大型", "大的", "大"), "large"),
        ]
        for aliases, value in chinese_sizes:
            if any(alias in raw for alias in aliases):
                result["size"] = value
                break
        size_patterns = [
            ("tiny", "tiny"),
            ("little", "little"),
            ("small", "small"),
            ("large", "large"),
            ("big", "large"),
        ]
        for phrase, value in size_patterns:
            if result["size"] is None and self._contains_word(normalized, phrase):
                result["size"] = value
                break

        chinese_positions = [
            (("左上角", "左上区域", "左上"), "upper-left"),
            (("右上角", "右上区域", "右上"), "upper-right"),
            (("左下角", "左下区域", "左下"), "lower-left"),
            (("右下角", "右下区域", "右下"), "lower-right"),
            (("中心", "中央", "中部"), "center"),
            (("左侧", "左边", "位于左", "在左", "左"), "left"),
            (("右侧", "右边", "位于右", "在右", "右"), "right"),
            (("上部", "顶部", "上方", "上"), "top"),
            (("下部", "底部", "下方", "下"), "bottom"),
        ]
