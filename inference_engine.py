    @staticmethod
    def _ensure_rgb_uint8(image: Any) -> np.ndarray:
        if image is None:
            raise ValueError("No image uploaded.")

        if isinstance(image, (str, Path)):
            bgr = _read_image(image, cv2.IMREAD_COLOR)
            if bgr is None:
                raise ValueError(
                    f"Invalid image or unreadable path: {image}"
                )
            arr = cv2.cvtColor(
                bgr,
                cv2.COLOR_BGR2RGB,
            )
            return arr

        if hasattr(image, "convert"):
            image = np.asarray(
                image.convert("RGB")
            )

        arr = np.asarray(image)

        if arr.size == 0:
            raise ValueError("Invalid image.")

        if arr.ndim == 2:
            arr = np.repeat(
                arr[..., None],
                3,
                axis=2,
            )
        elif arr.ndim == 3:
            if arr.shape[2] == 1:
                arr = np.repeat(
                    arr,
                    3,
                    axis=2,
                )
            elif arr.shape[2] >= 3:
                arr = arr[..., :3]
            else:
                raise ValueError(
                    f"Unsupported image shape: {arr.shape}"
                )
        else:
            raise ValueError(
                f"Unsupported image shape: {arr.shape}"
            )

        if np.issubdtype(arr.dtype, np.floating):
            max_value = float(
                np.nanmax(arr)
            )
            if max_value <= 1.0:
                arr = arr * 255.0

        arr = np.nan_to_num(
            arr,
            nan=0.0,
            posinf=255.0,
            neginf=0.0,
        )

        arr = np.clip(
            arr,
            0,
            255,
        ).astype(np.uint8)

        return np.ascontiguousarray(arr)

    def preprocess(
        self,
        image: Any,
    ) -> Tuple[np.ndarray, torch.Tensor]:
        original_rgb = self._ensure_rgb_uint8(
            image
        )

        resized = cv2.resize(
            original_rgb,
            (
                int(BASELINE.IMAGE_SIZE),
                int(BASELINE.IMAGE_SIZE),
            ),
            interpolation=cv2.INTER_LINEAR,
        )

        image_float = (
            resized.astype(np.float32) / 255.0
        )

        image_float = (
            image_float - IMAGENET_MEAN
        ) / IMAGENET_STD

        chw = np.transpose(
            image_float,
            (2, 0, 1),
        )

        tensor = (
            torch.from_numpy(chw)
            .float()
            .unsqueeze(0)
            .to(self.device)
        )

        return original_rgb, tensor

    @staticmethod
    def _prepare_gt_mask(
        gt_mask: Any,
        height: int,
        width: int,
    ) -> Optional[np.ndarray]:
        if gt_mask is None:
            return None

        if isinstance(gt_mask, (str, Path)):
            arr = _read_image(gt_mask, cv2.IMREAD_UNCHANGED)
            if arr is None:
                raise ValueError(
                    f"Cannot read GT mask: {gt_mask}"
                )
        elif hasattr(gt_mask, "convert"):
            arr = np.asarray(
                gt_mask.convert("L")
            )
        else:
            arr = np.asarray(gt_mask)

        if arr.ndim == 3:
            # Any nonzero RGB channel is foreground.
            binary = np.any(
                arr[..., :3] > 0,
                axis=2,
            )
        elif arr.ndim == 2:
            binary = arr > 0
        else:
            raise ValueError(
                f"Unsupported GT mask shape: {arr.shape}"
            )

        binary = binary.astype(np.uint8)

        if binary.shape != (height, width):
            binary = cv2.resize(
                binary,
                (width, height),
                interpolation=cv2.INTER_NEAREST,
            )
            binary = (
                binary > 0
            ).astype(np.uint8)

        return binary

    def _auto_ground_truth(
        self,
        image: Any,
        expression: str,
        height: int,
        width: int,
    ) -> Tuple[Optional[np.ndarray], Dict[str, Any]]:
        """
        Reconstruct the real Ref-EL-Defect GT mask from grefs(unc).json
        + instances.json.

        For correctness, automatic matching is intentionally conservative:
        the uploaded image basename and normalized expression must match one
        unique dataset reference. Ambiguous duplicate expressions are not
        guessed.
        """
        meta: Dict[str, Any] = {
            "GT Source": "Unavailable",
            "GT Match Status": "Not matched",
            "GT Dataset Image": None,
            "GT Ref ID": None,
            "GT Split": None,
            "GT Annotation IDs": None,
            "GT No-target": None,
        }

        if not isinstance(image, (str, Path)):
            meta["GT Match Status"] = (
                "Auto GT unavailable: input filename is not available. "
                "Upload an exact dataset image file or provide a GT mask."
            )
            return None, meta

        image_name = Path(image).name
        meta["GT Dataset Image"] = image_name

        norm = self._normalize_expression(expression)
        key = (image_name.lower(), norm)
        candidates = self._gt_sentence_index.get(key, [])

        # De-duplicate repeated identical payloads but keep genuinely ambiguous
        # dataset references separate.
        unique: Dict[
            Tuple[int, Tuple[int, ...], bool],
            Dict[str, Any],
        ] = {}
        for item in candidates:
            signature = (
                int(item.get("ref_id", -1)),
                tuple(int(x) for x in item.get("ann_ids", [])),
                bool(item.get("no_target", False)),
            )
            unique[signature] = item

        matches = list(unique.values())

        if not matches:
            meta["GT Match Status"] = (
                "No exact dataset GT match. Use the exact expression from "
                "grefs(unc).json for this image, or upload a manual GT mask."
            )
            return None, meta

        if len(matches) != 1:
            meta["GT Match Status"] = (
                f"Ambiguous dataset expression ({len(matches)} matches). "
                "Auto GT disabled to avoid choosing the wrong annotation."
            )
            return None, meta

        ref = matches[0]
        ann_ids = [
            int(aid)
            for aid in ref.get("ann_ids", [])
        ]
        no_target = bool(ref.get("no_target", False))

        meta.update(
            {
                "GT Source": "Auto Ref-EL-Defect annotation",
                "GT Match Status": (
                    "Exact dataset match"
                    + (" (no-target)" if no_target else "")
                ),
                "GT Ref ID": int(ref.get("ref_id", -1)),
                "GT Split": str(ref.get("split", "")),
                "GT Annotation IDs": ann_ids,
                "GT No-target": no_target,
            }
        )

        # A real no-target reference has an all-background GT mask.
        if no_target:
            return np.zeros(
                (height, width),
                dtype=np.uint8,
            ), meta

        image_meta = self._image_meta_by_filename.get(
            image_name.lower()
        )
        if image_meta is None:
            meta["GT Source"] = "Unavailable"
            meta["GT Match Status"] = (
                f"Image metadata not found in instances.json: {image_name}"
            )
            return None, meta

        native_h = int(image_meta.get("height", 0))
        native_w = int(image_meta.get("width", 0))

        if native_h <= 0 or native_w <= 0:
            meta["GT Source"] = "Unavailable"
            meta["GT Match Status"] = (
                "Invalid image dimensions in instances.json."
            )
            return None, meta

        mask = np.zeros(
            (native_h, native_w),
            dtype=np.uint8,
        )

        valid_ann_count = 0

        for ann_id in ann_ids:
            if ann_id < 0:
                continue

            ann = self._ann_by_id.get(int(ann_id))
            if ann is None:
                continue

            valid_ann_count += 1
            segmentation = ann.get("segmentation", [])

            # This dataset uses COCO polygon lists (iscrowd=0).
            if not isinstance(segmentation, list):
                continue

            for polygon in segmentation:
                pts = np.asarray(
                    polygon,
                    dtype=np.float32,
                ).reshape(-1, 2)

                if pts.shape[0] < 3:
                    continue

                pts[:, 0] = np.clip(
                    pts[:, 0],
                    0,
                    native_w - 1,
                )
                pts[:, 1] = np.clip(
                    pts[:, 1],
                    0,
                    native_h - 1,
                )

                cv2.fillPoly(
                    mask,
                    [
                        np.rint(pts).astype(
                            np.int32
                        )
                    ],
                    1,
                )

        if valid_ann_count == 0:
            meta["GT Source"] = "Unavailable"
            meta["GT Match Status"] = (
                "Matched dataset reference, but its annotation IDs were "
                "not found in instances.json."
            )
            return None, meta

        if mask.shape != (height, width):
            mask = cv2.resize(
                mask,
                (width, height),
                interpolation=cv2.INTER_NEAREST,
            )
            mask = (mask > 0).astype(np.uint8)

        return mask, meta

    def _ref_semantic_signature(
        self,
        ref: Dict[str, Any],
    ) -> Dict[str, Optional[str]]:
        """Extract only dataset-supported semantics from one reference."""
        values: Dict[str, set] = {
            "defect_type": set(), "size": set(),
            "position": set(), "busbar_relation": set(),
        }
        for sentence in ref.get("sentences", []):
            parsed = self.parse_expression_fields(sentence)
            for key, value in parsed.items():
                if value:
                    values[key].add(value)

        # Category IDs are real annotation metadata. Use a single category as
        # a safe category signal when wording itself is generic ("all defects").
        category_ids = {
            int(cid) for cid in ref.get("category_ids", [])
            if int(cid) in {int(info["id"]) for info in self._defect_by_label.values()}
        }
        if not values["defect_type"] and len(category_ids) == 1:
            category_id = next(iter(category_ids))
            for label, info in self._defect_by_label.items():
                if int(info["id"]) == category_id:
                    values["defect_type"].add(label)
                    break

        # Ref sentences are paraphrases. Conflicting values are deliberately
        # treated as unspecified rather than choosing a likely interpretation.
        return {
            key: next(iter(value_set)) if len(value_set) == 1 else None
            for key, value_set in values.items()
        }

    @staticmethod
    def _condition_value(value: Any) -> Optional[str]:
        value = str(value or "").strip()
        return None if not value or value == "Not specified" else value

    def _find_semantic_target_set(
        self,
        image_name: str,
        conditions: Dict[str, Any],
    ) -> Tuple[Optional[Dict[str, Any]], str]:
        requested = {
            key: self._condition_value(conditions.get(key))
            for key in ("defect_type", "size", "busbar_relation")
        }
        refs = self._refs_by_filename.get(image_name.lower(), [])
        matched = []
        for ref in refs:
            signature = self._ref_semantic_signature(ref)
            if all(
                value is None or signature.get(key) == value
                for key, value in requested.items()
            ):
                matched.append(ref)

        if not matched:
            return None, "No reliable dataset annotation supports the requested Defect Type / Size / Busbar Relation combination."

        by_target: Dict[Tuple[Tuple[int, ...], bool], List[Dict[str, Any]]] = {}
        for ref in matched:
            ann_ids = tuple(sorted(
                int(ann_id) for ann_id in ref.get("ann_ids", [])
                if int(ann_id) >= 0
            ))
            by_target.setdefault((ann_ids, bool(ref.get("no_target", False))), []).append(ref)

        if len(by_target) != 1:
            return None, "Multiple dataset target sets match the requested semantic conditions."

        (ann_ids, no_target), target_refs = next(iter(by_target.items()))
        return {
            "ann_ids": list(ann_ids), "no_target": no_target,
            "refs": target_refs,
        }, "Unique semantic target match"

    def _annotation_centroid(
        self,
        ann: Dict[str, Any],
    ) -> Optional[Tuple[float, float]]:
        bbox = ann.get("bbox")
        if isinstance(bbox, list) and len(bbox) >= 4:
            return float(bbox[0]) + float(bbox[2]) / 2.0, float(bbox[1]) + float(bbox[3]) / 2.0
        points = []
        for polygon in ann.get("segmentation", []):
            if isinstance(polygon, list) and len(polygon) >= 6:
                array = np.asarray(polygon, dtype=np.float32).reshape(-1, 2)
                points.append(array)
        if not points:
            return None
        merged = np.concatenate(points, axis=0)
        return float(merged[:, 0].mean()), float(merged[:, 1].mean())

    def _filter_annotations_by_position(
        self,
        ann_ids: List[int],
        position: Optional[str],
        width: int,
        height: int,
    ) -> List[int]:
        position = self._condition_value(position)
        if position is None:
            return list(ann_ids)
        selected = []
        for ann_id in ann_ids:
            ann = self._ann_by_id.get(int(ann_id))
            centroid = self._annotation_centroid(ann) if ann else None
            if centroid is None:
                continue
            x, y = centroid
            matched = {
                "left": x < width / 2, "right": x >= width / 2,
                "top": y < height / 2, "bottom": y >= height / 2,
                "center": width * .25 <= x < width * .75 and height * .25 <= y < height * .75,
                "upper-left": x < width / 2 and y < height / 2,
                "upper-right": x >= width / 2 and y < height / 2,
                "lower-left": x < width / 2 and y >= height / 2,
                "lower-right": x >= width / 2 and y >= height / 2,
            }.get(position, False)
            if matched:
                selected.append(int(ann_id))
        return selected

    def _render_gt_from_ann_ids(
        self,
        ann_ids: List[int],
        image_name: str,
        height: int,
        width: int,
    ) -> Optional[np.ndarray]:
        image_meta = self._image_meta_by_filename.get(image_name.lower())
        if image_meta is None:
            return None
        native_h, native_w = int(image_meta["height"]), int(image_meta["width"])
        if native_h <= 0 or native_w <= 0:
            return None
        mask = np.zeros((native_h, native_w), dtype=np.uint8)
        for ann_id in ann_ids:
            ann = self._ann_by_id.get(int(ann_id))
            if ann is None:
                return None
            for polygon in ann.get("segmentation", []):
                if not isinstance(polygon, list) or len(polygon) < 6:
                    continue
                points = np.asarray(polygon, dtype=np.float32).reshape(-1, 2)
                points[:, 0] = np.clip(points[:, 0], 0, native_w - 1)
                points[:, 1] = np.clip(points[:, 1], 0, native_h - 1)
                cv2.fillPoly(mask, [np.rint(points).astype(np.int32)], 1)
        if mask.shape != (height, width):
            mask = cv2.resize(mask, (width, height), interpolation=cv2.INTER_NEAREST)
        return (mask > 0).astype(np.uint8)

    def _condition_aware_ground_truth(
        self,
        image: Any,
        conditions: Dict[str, Any],
        height: int,
        width: int,
    ) -> Tuple[Optional[np.ndarray], Dict[str, Any]]:
        meta: Dict[str, Any] = {
            "GT Source": "Unavailable", "GT Match Status": "Not matched",
            "GT Dataset Image": None, "GT Ref ID": None, "GT Split": None,
            "GT Annotation IDs": None, "GT No-target": None,
            "GT Conditions": None, "Matched Ref IDs": None,
            "Position Filter": self._condition_value(conditions.get("position")),
        }
        if not isinstance(image, (str, Path)):
            meta["GT Match Status"] = "Auto GT unavailable: input filename is not available."
            return None, meta
        image_name = Path(image).name
        meta["GT Dataset Image"] = image_name
        target, status = self._find_semantic_target_set(image_name, conditions)
        if target is None:
            meta["GT Match Status"] = status
            return None, meta
        position = self._condition_value(conditions.get("position"))
        if target["no_target"] and position:
            meta["GT Match Status"] = "No-target reference cannot verify a requested Position condition."
            return None, meta
        ann_ids = self._filter_annotations_by_position(target["ann_ids"], position, width, height)
        refs = target["refs"]
        meta.update({
            "GT Source": "Condition-aware Dataset GT",
            "GT Match Status": status + ("; no matching annotation in selected region" if position and not ann_ids else ""),
            "GT Ref ID": refs[0].get("ref_id") if len(refs) == 1 else None,
            "Matched Ref IDs": [ref.get("ref_id") for ref in refs],
            "GT Split": refs[0].get("split") if len(refs) == 1 else "multiple",
            "GT Annotation IDs": ann_ids,
            "GT No-target": bool(target["no_target"]),
            "Position Filter": position,
            "GT Conditions": ", ".join(f"{key}={value}" for key, value in conditions.items() if self._condition_value(value)),
        })
        if target["no_target"]:
            return np.zeros((height, width), dtype=np.uint8), meta
        mask = self._render_gt_from_ann_ids(ann_ids, image_name, height, width)
        if mask is None:
            meta["GT Source"] = "Unavailable"
            meta["GT Match Status"] = "Matched dataset target, but its annotation geometry could not be rendered."
        return mask, meta

    def _resolve_ground_truth(
        self,
        image: Any,
        expression: str,
        gt_mask: Any,
        height: int,
        width: int,
        query_conditions: Optional[Dict[str, Any]] = None,
    ) -> Tuple[Optional[np.ndarray], Dict[str, Any]]:
        # A manually uploaded GT always takes priority.
        if gt_mask is not None:
            gt_binary = self._prepare_gt_mask(
                gt_mask,
                height=height,
                width=width,
            )
            return gt_binary, {
                "GT Source": "Manual GT mask",
                "GT Match Status": "Manual GT provided",
                "GT Dataset Image": (
                    Path(image).name
                    if isinstance(image, (str, Path))
                    else None
                ),
                "GT Ref ID": None,
                "GT Split": None,
                "GT Annotation IDs": None,
                "GT No-target": bool(
                    gt_binary is not None
                    and int(gt_binary.sum()) == 0
                ),
            }

        conditions = query_conditions or {}
        # Preserve the exact dataset expression path when no position filter
        # is requested. It remains the strongest possible GT verification.
        if not self._condition_value(conditions.get("position")):
            exact_mask, exact_meta = self._auto_ground_truth(
                image=image, expression=expression, height=height, width=width,
            )
            if exact_mask is not None:
                exact_meta["GT Conditions"] = ", ".join(
                    f"{key}={value}" for key, value in conditions.items()
                    if self._condition_value(value)
                )
                exact_meta["Matched Ref IDs"] = [exact_meta.get("GT Ref ID")]
                exact_meta["Position Filter"] = None
                return exact_mask, exact_meta

        return self._condition_aware_ground_truth(
            image=image, conditions=conditions, height=height, width=width,
        )

