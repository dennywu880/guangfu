    @torch.inference_mode()
    def infer(
        self,
        image: Any,
        expression: str,
        gt_mask: Any = None,
        query_conditions: Optional[Dict[str, Any]] = None,
        original_expression: Optional[str] = None,
    ) -> Dict[str, Any]:
        expression = str(
            expression or ""
        ).strip()

        if not expression:
            raise ValueError(
                "Text expression is empty."
            )

        original_rgb, image_tensor = (
            self.preprocess(image)
        )

        original_h, original_w = (
            original_rgb.shape[:2]
        )

        gt_binary, gt_meta = self._resolve_ground_truth(
            image=image,
            expression=expression,
            gt_mask=gt_mask,
            height=original_h,
            width=original_w,
            query_conditions=query_conditions,
        )

        if self.device.type == "cuda":
            torch.cuda.synchronize()

        start_time = time.perf_counter()

        # --------------------------------------------------------------
        # General model + ONLINE BERT
        # --------------------------------------------------------------
        self.hook.value = None

        if self.use_shared_moe:
            general_logits, shared_context = self.shared_moe.forward_general(
                image_tensor, texts=[expression],
            )
            pooled_text = shared_context.pooled_text.detach().float()
        else:
            debug = self.general_model(
                image_tensor,
                texts=[expression],
                return_debug=True,
            )
            general_logits = debug["logits"]
            pooled_text = debug["pooled_text"].detach().float()

        deep = self.hook.value
        if deep is None:
            raise RuntimeError(
                "Presence feature hook was not triggered."
            )

        image_feature = (
            self._image_feature_from_hook(deep)
            .float()
        )

        general_probs = torch.sigmoid(
            general_logits
        )

        stats, stat_values = (
            self._general_stats(
                general_probs
            )
        )

        general_ratio = stat_values["area050"]
        general_pred = (
            general_probs
            >= BASELINE.GENERAL_MASK_THRESHOLD
        )
        general_area = int(
            general_pred.sum().item()
        )

        # --------------------------------------------------------------
        # Frozen Router
        # --------------------------------------------------------------
        (
            branch,
            route_source,
            text_size,
        ) = BASELINE.route_sample(
            text=expression,
            pred_ratio=general_ratio,
        )

        route_features = torch.tensor(
            [
                BASELINE.route_onehot(branch)
            ],
            dtype=torch.float32,
            device=self.device,
        )

        text_cues = torch.tensor(
            [
                BASELINE.text_onehot(
                    text_size
                )
            ],
            dtype=torch.float32,
            device=self.device,
        )

        # --------------------------------------------------------------
        # Presence Gate v2 - same feature order as final TestB
        # --------------------------------------------------------------
        gate_x = torch.cat(
            [
                image_feature,
                pooled_text,
                stats.float(),
                route_features,
                text_cues,
            ],
            dim=1,
        )

        expected_dim = int(
            self.gate_mean.shape[1]
        )

        if gate_x.shape[1] != expected_dim:
            raise RuntimeError(
                "Presence Gate input dimension mismatch: "
                f"built={gate_x.shape[1]}, "
                f"checkpoint expects={expected_dim}."
            )

        gate_z = (
            gate_x - self.gate_mean
        ) / self.gate_std

        p_no_target = float(
            torch.sigmoid(
                self.gate(gate_z)
            )[0].item()
        )

        gate_reject = bool(
            p_no_target
            >= float(self.gate_threshold)
        )

        target_probability = float(
            1.0 - p_no_target
        )

        final_probs_384 = None
        selected_expert = None
        mean_foreground_probability = None

        if gate_reject:
            final_pred_384 = np.zeros(
                (
                    int(BASELINE.IMAGE_SIZE),
                    int(BASELINE.IMAGE_SIZE),
                ),
                dtype=np.uint8,
            )
            selected_expert = (
                "None (Presence Gate rejected)"
            )
            presence_result = "No Target"
            status = (
                "No target defect detected by Presence Gate v2."
            )

        else:
            if self.use_shared_moe:
                expert_logits = self.shared_moe.forward_expert(
                    shared_context, branch,
                )
            else:
                expert = self._activate_expert(branch)
                expert_logits = expert(
                    image_tensor, pooled_text=pooled_text,
                )

            final_probs_384 = torch.sigmoid(
                expert_logits
            )

            final_pred_tensor = (
                final_probs_384
                >= BASELINE.EXPERT_MASK_THRESHOLD
            )

            final_pred_384 = (
                final_pred_tensor[0, 0]
                .detach()
                .cpu()
                .numpy()
                .astype(np.uint8)
            )

            fg = final_pred_tensor
            if bool(fg.any().item()):
                mean_foreground_probability = float(
                    final_probs_384[fg]
                    .mean()
                    .item()
                )

            selected_expert = branch
            presence_result = "Target"

            if int(final_pred_384.sum()) == 0:
                status = (
                    "Target passed Presence Gate, but the selected "
                    "expert produced an empty mask."
                )
            else:
                status = (
                    "Inference completed successfully."
                )

        # Binary mask is thresholded at model resolution first, exactly as
        # final TestB, then restored to original image size with nearest-neighbor.
        final_mask_original = cv2.resize(
            final_pred_384,
            (original_w, original_h),
            interpolation=cv2.INTER_NEAREST,
        )
        final_mask_original = (
            final_mask_original > 0
        ).astype(np.uint8)

        position = self._condition_value(
            (query_conditions or {}).get("position")
        )
        region_mask = self._region_mask(
            original_h, original_w, position
        )
        # The model always produces its raw mask for the whole image.  Position
        # then selects complete connected components by centroid; it never
        # changes the model query or cuts one predicted defect at a boundary.
        raw_mask_original = final_mask_original.copy()
        raw_pred_instances = self.extract_prediction_instances(raw_mask_original)
        selected_pred_instances = [
            instance for instance in raw_pred_instances
            if self._instance_in_position(instance, position, original_w, original_h)
        ]
        final_mask_original = self.union_instance_masks(
            selected_pred_instances, original_h, original_w
        )

        (
            mask_255,
            overlay_rgb,
            contour_rgb,
        ) = self._make_visuals(
            original_rgb,
            final_mask_original,
        )

        gt_mask_255 = (
            None
            if gt_binary is None
            else (
                gt_binary.astype(np.uint8)
                * 255
            )
        )

        comparison_rgb = self._make_gt_comparison(
            original_rgb=original_rgb,
            pred_mask=final_mask_original,
            gt_mask=gt_binary,
        )

        metrics = self.calculate_metrics(
            final_mask_original,
            gt_binary,
            valid_mask=region_mask,
        )

