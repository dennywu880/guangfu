    @staticmethod
    def calculate_metrics(
        pred_mask: np.ndarray,
        gt_mask: Optional[np.ndarray],
        valid_mask: Optional[np.ndarray] = None,
    ) -> Dict[str, Optional[float]]:
        if gt_mask is None:
            return {
                "Pixel Accuracy": None,
                "Dice": None,
                "IoU": None,
                "Precision": None,
                "Recall": None,
                "Specificity": None,
                "F1": None,
                "TP Pixels": None,
                "FP Pixels": None,
                "FN Pixels": None,
                "TN Pixels": None,
            }

        pred = pred_mask.astype(bool)
        gt = gt_mask.astype(bool)
        valid = np.ones_like(pred, dtype=bool) if valid_mask is None else valid_mask.astype(bool)

        tp = int(np.logical_and(np.logical_and(pred, gt), valid).sum())
        fp = int(
            np.logical_and(
                pred,
                np.logical_and(np.logical_not(gt), valid),
            ).sum()
        )
        fn = int(
            np.logical_and(
                np.logical_not(pred),
                np.logical_and(gt, valid),
            ).sum()
        )
        tn = int(
            np.logical_and(
                np.logical_not(pred),
                np.logical_and(np.logical_not(gt), valid),
            ).sum()
        )

        pred_sum = tp + fp
        gt_sum = tp + fn
        union = tp + fp + fn
        total = tp + fp + fn + tn

        pixel_accuracy = (
            None
            if total == 0
            else (tp + tn) / total
        )

        empty_gt = gt_sum == 0
        dice = None if empty_gt and pred_sum == 0 else (0.0 if empty_gt else (2.0 * tp) / (pred_sum + gt_sum))
        iou = None if empty_gt and pred_sum == 0 else (0.0 if empty_gt else tp / union)

        if empty_gt and pred_sum == 0:
            precision = None
        elif empty_gt:
            precision = 0.0
        elif (tp + fp) == 0:
            precision = 0.0
        else:
            precision = tp / (tp + fp)

        if (tp + fn) == 0:
            recall = None
        else:
            recall = tp / (tp + fn)

        if (tn + fp) == 0:
            specificity = 1.0
        else:
            specificity = tn / (tn + fp)

        f1_denom = None if precision is None or recall is None else precision + recall
        f1 = (
            None
            if f1_denom is None
            else 0.0 if f1_denom == 0
            else (
                2.0
                * precision
                * recall
                / f1_denom
            )
        )

        return {
            "Pixel Accuracy": (
                None
                if pixel_accuracy is None
                else float(pixel_accuracy)
            ),
            "Dice": None if dice is None else float(dice),
            "IoU": None if iou is None else float(iou),
            "Precision": None if precision is None else float(precision),
            "Recall": None if recall is None else float(recall),
            "Specificity": float(specificity),
            "F1": None if f1 is None else float(f1),
            "TP Pixels": int(tp),
            "FP Pixels": int(fp),
            "FN Pixels": int(fn),
            "TN Pixels": int(tn),
        }

