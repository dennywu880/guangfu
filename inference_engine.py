    @staticmethod
    def _image_feature_from_hook(
        deep: torch.Tensor,
    ) -> torch.Tensor:
        if deep.ndim == 4:
            return deep.mean(dim=(2, 3))
        if deep.ndim == 2:
            return deep
        return deep.flatten(1)

    @staticmethod
    def _general_stats(
        probs: torch.Tensor,
    ) -> Tuple[torch.Tensor, Dict[str, float]]:
        flat = probs.flatten(1)

        mean = flat.mean(dim=1)
        std = flat.std(
            dim=1,
            unbiased=False,
        )
        maxv = flat.max(
            dim=1
        ).values
        q95 = torch.quantile(
            flat,
            0.95,
            dim=1,
        )
        q99 = torch.quantile(
            flat,
            0.99,
            dim=1,
        )

        eps = 1e-6
        p = probs.clamp(
            eps,
            1.0 - eps,
        )

        entropy = -(
            p * p.log()
            + (1.0 - p)
            * (1.0 - p).log()
        ).flatten(1).mean(dim=1)

        area010 = (
            (flat >= 0.10)
            .float()
            .mean(dim=1)
        )
        area030 = (
            (flat >= 0.30)
            .float()
            .mean(dim=1)
        )
        area050 = (
            (flat >= 0.50)
            .float()
            .mean(dim=1)
        )
        area070 = (
            (flat >= 0.70)
            .float()
            .mean(dim=1)
        )
        area090 = (
            (flat >= 0.90)
            .float()
            .mean(dim=1)
        )

        fg050 = (
            (flat >= 0.50)
            .float()
        )
        fg_count = fg050.sum(dim=1)

        fg_mean050 = torch.where(
            fg_count > 0,
            (flat * fg050).sum(dim=1)
            / fg_count.clamp_min(1.0),
            torch.zeros_like(fg_count),
        )

        stats = torch.stack(
            [
                mean,
                std,
                maxv,
                q95,
                q99,
                entropy,
                area010,
                area030,
                area050,
                area070,
                area090,
                fg_mean050,
            ],
            dim=1,
        )

        scalars = {
            "mean": float(mean[0].item()),
            "std": float(std[0].item()),
            "max": float(maxv[0].item()),
            "q95": float(q95[0].item()),
            "q99": float(q99[0].item()),
            "entropy": float(entropy[0].item()),
            "area010": float(area010[0].item()),
            "area030": float(area030[0].item()),
            "area050": float(area050[0].item()),
            "area070": float(area070[0].item()),
            "area090": float(area090[0].item()),
            "fg_mean050": float(
                fg_mean050[0].item()
            ),
        }

        return stats, scalars

